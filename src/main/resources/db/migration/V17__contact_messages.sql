CREATE TABLE contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(254) NOT NULL,
    question TEXT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'HANDLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handled_at TIMESTAMPTZ,
    handled_by VARCHAR(254)
);
CREATE INDEX idx_contact_messages_status_time ON contact_messages (status, created_at DESC);

ALTER TABLE email_outbox ALTER COLUMN order_id DROP NOT NULL;
ALTER TABLE email_outbox ADD COLUMN contact_id BIGINT REFERENCES contact_messages(id);
ALTER TABLE email_outbox ADD CONSTRAINT chk_email_outbox_source
    CHECK ((order_id IS NULL) <> (contact_id IS NULL));
CREATE UNIQUE INDEX ux_email_outbox_contact_kind ON email_outbox (contact_id, kind);
