CREATE TABLE promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_prefix VARCHAR(16) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    discount_percent NUMERIC(5, 2) NOT NULL CHECK (discount_percent > 0 AND discount_percent <= 50),
    minimum_total NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (minimum_total >= 0),
    new_customer_only BOOLEAN NOT NULL DEFAULT FALSE,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    starts_at TIMESTAMPTZ NOT NULL,
    ends_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_promotions_dates CHECK (ends_at IS NULL OR ends_at > starts_at)
);

CREATE TABLE customer_promotion_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promotion_id BIGINT NOT NULL REFERENCES promotions(id),
    customer_account_id BIGINT NOT NULL REFERENCES customer_accounts(id),
    code VARCHAR(32) NOT NULL UNIQUE,
    reserved_group VARCHAR(32),
    reserved_until TIMESTAMPTZ,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ux_customer_promotion UNIQUE (promotion_id, customer_account_id),
    CONSTRAINT ck_promotion_reservation CHECK ((reserved_group IS NULL) = (reserved_until IS NULL))
);

