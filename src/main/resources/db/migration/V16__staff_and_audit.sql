CREATE TABLE staff_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    full_name VARCHAR(150) NOT NULL,
    password_hash VARCHAR(60) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    session_version INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ
);

ALTER TABLE customer_accounts ADD COLUMN enabled BOOLEAN NOT NULL DEFAULT TRUE;

CREATE TABLE account_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_role VARCHAR(16) NOT NULL,
    actor_id VARCHAR(254) NOT NULL,
    action VARCHAR(64) NOT NULL,
    target_type VARCHAR(32),
    target_id VARCHAR(64),
    request_path VARCHAR(250),
    ip_address VARCHAR(64),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_account_audit_events_time ON account_audit_events (occurred_at DESC);
CREATE INDEX idx_account_audit_events_actor ON account_audit_events (actor_role, actor_id, occurred_at DESC);
