CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    species VARCHAR(120) NOT NULL,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    description TEXT,
    image_url VARCHAR(500),
    scientific_name VARCHAR(150),
    species_group VARCHAR(30) DEFAULT 'OTHER',
    gender VARCHAR(20),
    birth_date DATE,
    approximate_age VARCHAR(100),
    current_size VARCHAR(120),
    adult_size VARCHAR(120),
    origin VARCHAR(20),
    care_difficulty VARCHAR(20),
    individual_code VARCHAR(100),
    video_url VARCHAR(500),
    status VARCHAR(20) NOT NULL CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD'))
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_products_individual_code ON products (individual_code) WHERE individual_code IS NOT NULL;

CREATE TABLE IF NOT EXISTS product_images (
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    image_url VARCHAR(500) NOT NULL,
    PRIMARY KEY (product_id, position)
);
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id),
    customer_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    address VARCHAR(500),
    fulfillment_method VARCHAR(20) NOT NULL CHECK (fulfillment_method IN ('DELIVERY', 'PICKUP')),
    note TEXT,
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'CONFIRMED', 'CANCELLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_orders_product_id ON orders(product_id);
