CREATE TABLE warranty_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    order_code VARCHAR(10) NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    customer_name VARCHAR(150) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(254) NOT NULL,
    description TEXT NOT NULL,
    video_file VARCHAR(80) NOT NULL,
    video_content_type VARCHAR(40) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'NEW' CHECK (status IN ('NEW', 'HANDLED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handled_at TIMESTAMPTZ,
    handled_by VARCHAR(254)
);
CREATE INDEX idx_warranty_claims_status_time ON warranty_claims (status, created_at DESC);
